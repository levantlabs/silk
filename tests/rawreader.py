"""The nutmeg reader under test.

A single import indirection for the rawfile conformance suite
(``tests/test_rawfile_reader.py``), so the suite is written against the
*format specification* rather than against one implementation's internals.

The suite's expected values derive only from the published nutmeg/rawfile
format, from real rawfiles generated by ngspice-42 and Xyce 7.10, from
ASCII-vs-binary cross-validation of the same simulator run, and from what the
circuit under test must physically do. No third-party reader is involved.
"""


def read_raw(path):
    """Parse a nutmeg rawfile with the reader under test."""
    from silk.signals.rawfile import read_rawfile
    return read_rawfile(str(path))
