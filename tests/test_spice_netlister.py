class TestGenerateHeader:

    @pytest.mark.parametrize('name', [
        'my_amplifier', 'My LNA (rev. 2): gain=20dB / in-out; $bias #1',
    ])
    def test_header_title_and_provenance(self, netlister, name):
        """SPICE consumes line one as its title, including the comment prefix."""
        assert netlister.generate_header(name).splitlines() == [
            f'*** Circuit: {name}',
            '*** Automated netlist generator',
            '*** Generated by silk',
        ]

    def test_header_contains_default_name(self, netlister):
        """generate_header() with no args uses 'circuit' as default."""
        header = netlister.generate_header()
        assert header.splitlines()[0] == '*** Circuit: circuit'

    @pytest.mark.parametrize('name', [None, '', ' \t\r\n'])
    def test_header_blank_name_has_stable_title(self, netlister, name):
        assert netlister.generate_header(name).splitlines()[0] == '*** Circuit: circuit'

    def test_multiline_name_stays_on_title_line(self, netlister):
        header = netlister.generate_header('My LNA\r\n.end\nrevision 2')
        assert header.splitlines()[0] == '*** Circuit: My LNA .end revision 2'
        assert len(header.splitlines()) == 3

    def test_header_is_comment(self, netlister):
        """Header lines should be SPICE comments (start with ***)."""
        header = netlister.generate_header('test')
        for line in header.strip().split('\n'):
            assert line.startswith('***')


