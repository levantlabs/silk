class TestSubcktUniqueness:
    """One `.subckt` definition per module, however deep the hierarchy.

    `uniqueModules` dedupes only within one level, but each recursive
    `generate_netlist(subckt=True)` re-emits its own children — so a leaf
    instantiated from two parents used to be defined once per parent.
    Redefinition has no meaning in SPICE (which definition wins is
    implementation-defined); ngspice silently picks one, which is why this
    went unnoticed until a stricter parser refused the deck.
    """

    def _leaf(self, pdk, tmp_dir, name):
        from silk.circuit.modules import Module
        m = Module('PDK_skywater130', tmp_dir, f'{name}.cir', pdk_details=pdk)
        m.define_module_name(name)
        m.define_module_nets({'a': None, 'y': None, 'vdd': None, 'vss': None})
        m.add(pdk.nmos1p8('mn', d='y', g='a', s='vss', b='vss', w=1, l=0.15, m=1))
        return m

    @pytest.mark.parametrize('capture', [False, True])
    def test_leaf_shared_by_two_parents_is_defined_once(self, pdk, tmp_dir, capture):
        """The div24 shape: two mid-level blocks both containing the same leaf."""
        import re
        from silk.circuit.modules import Module

        leaf = self._leaf(pdk, tmp_dir, 'leafcell')

        mids = []
        for mid_name in ('blocka', 'blockb'):
            mid = Module('PDK_skywater130', tmp_dir, f'{mid_name}.cir',
                           pdk_details=pdk)
            mid.define_module_name(mid_name)
            mid.define_module_nets({'a': None, 'y': None,
                                    'vdd': None, 'vss': None})
            mid.add_module(leaf, 'xleaf',
                            nets={'a': 'a', 'y': 'y', 'vdd': 'vdd', 'vss': 'vss'})
            mids.append(mid)

        top = Module('PDK_skywater130', tmp_dir, 'top.cir', pdk_details=pdk)
        for i, mid in enumerate(mids):
            top.add_module(mid, f'xmid{i}',
                            nets={'a': 'na', 'y': f'ny{i}',
                                  'vdd': 'vdd', 'vss': '0'})

        wrappers = {}
        emitted = set()
        netlist = top.netlister.generate_module_definitions(
            top.module_dict,
            terminal_current_method='ammeter_wrapper' if capture else None,
            ammeter_wrappers=wrappers, emitted=emitted)
        assert emitted == {'blocka', 'blockb', 'leafcell'}
        assert len(wrappers) == (1 if capture else 0)
        if capture:
            top.save_device_currents = True
            top.terminal_current_method = 'ammeter_wrapper'
            top.add_sim_type(Transient(step=1e-9, stop=10e-9))
            from pathlib import Path
            deck = Path(top.generate_netlist()).read_text().lower()
            assert deck.count('.subckt amm_sky130_fd_pr__nfet_01v8') == 1
            assert deck.count('.subckt leafcell ') == 1
        names = [m.lower() for m in
                 re.findall(r'(?im)^\.subckt\s+(\S+)', netlist)]

        assert names.count('leafcell') == 1, (
            f'leafcell defined {names.count("leafcell")}x — one per parent. '
            f'Definitions emitted: {names}')
        assert len(names) == len(set(names)), f'duplicate definitions: {names}'

    # -- The second failure mode: two *structurally different* modules sharing
    #    one module_name. The name-keyed module_dict used to keep the first body
    #    and silently drop the second, so every instance of the second referenced
    #    the wrong .subckt. register_module_definition now fails loud on it.

    def _leaf2(self, pdk, tmp_dir, name):
        """A structurally *different* leaf under a caller-chosen name (two
        transistors instead of one), for the collision tests."""
        from silk.circuit.modules import Module
        m = Module('PDK_skywater130', tmp_dir, f'{name}.cir', pdk_details=pdk)
        m.define_module_name(name)
        m.define_module_nets({'a': None, 'y': None, 'vdd': None, 'vss': None})
        m.add(pdk.nmos1p8('mn', d='y', g='a', s='vss', b='vss', w=1, l=0.15, m=1))
        m.add(pdk.nmos1p8('mn2', d='y', g='a', s='vss', b='vss', w=2, l=0.15, m=1))
        return m

    def test_two_distinct_modules_same_name_raises(self, pdk, tmp_dir):
        from silk.circuit.modules import Module
        from silk.exceptions import CircuitError

        a = self._leaf(pdk, tmp_dir, 'shared')     # one-transistor body
        b = self._leaf2(pdk, tmp_dir, 'shared')    # two-transistor body, SAME name

        top = Module('PDK_skywater130', tmp_dir, 'top.cir', pdk_details=pdk)
        top.add_module(a, 'xa', nets={'a': 'na', 'y': 'y0',
                                       'vdd': 'vdd', 'vss': '0'})
        top.add_module(b, 'xb', nets={'a': 'na', 'y': 'y1',
                                      'vdd': 'vdd', 'vss': '0'})
        with pytest.raises(CircuitError, match='structurally different'):
            top.generate_netlist()

    def test_same_module_reused_does_not_raise(self, pdk, tmp_dir):
        from silk.circuit.modules import Module

        leaf = self._leaf(pdk, tmp_dir, 'reused')
        top = Module('PDK_skywater130', tmp_dir, 'top.cir', pdk_details=pdk)
        top.add_module(leaf, 'x0', nets={'a': 'na', 'y': 'y0',
                                          'vdd': 'vdd', 'vss': '0'})
        top.add_module(leaf, 'x1', nets={'a': 'na', 'y': 'y1',
                                          'vdd': 'vdd', 'vss': '0'})
        assert top.module_dict['reused']['numberInstantiated'] == 2

    def test_identical_rebuild_same_name_does_not_raise(self, pdk, tmp_dir):
        """Two *distinct* objects with byte-identical structure and the same name
        are a legitimate rebuild, not a collision — deduped, never rejected."""
        from silk.circuit.modules import Module

        a = self._leaf(pdk, tmp_dir, 'twin')
        b = self._leaf(pdk, tmp_dir, 'twin')   # different object, identical body
        assert a is not b

        top = Module('PDK_skywater130', tmp_dir, 'top.cir', pdk_details=pdk)
        top.add_module(a, 'xa', nets={'a': 'na', 'y': 'y0',
                                       'vdd': 'vdd', 'vss': '0'})
        top.add_module(b, 'xb', nets={'a': 'na', 'y': 'y1',
                                       'vdd': 'vdd', 'vss': '0'})   # must not raise
        assert top.module_dict['twin']['numberInstantiated'] == 2

    # -- TASK-327: module_names differing only by case. SPICE .subckt names
    #    are case-insensitive (ngspice folds to lower, Xyce to upper), so
    #    'Bias' and 'bias' are ONE namespace entry to the simulator even
    #    though the name-keyed module_dict used to treat them as two
    #    independent keys — emitting two `.subckt` blocks that ngspice
    #    silently collapses into one, with every instance of the discarded
    #    body silently reading the wrong body's values. Reproducer measured
    #    by the reviewer on main @ec1c08a2 (v1#branch = -2.000e-3 instead of
    #    the correct -1.5e-3 for sibling 1k/2k resistors sharing 'Bias'/'bias').

    def test_case_variant_module_names_different_bodies_raises(self, pdk, tmp_dir):
        from silk.circuit.modules import Module
        from silk.exceptions import CircuitError

        a = self._leaf(pdk, tmp_dir, 'Bias')       # one-transistor body
        b = self._leaf2(pdk, tmp_dir, 'bias')      # two-transistor body, case-variant name

        top = Module('PDK_skywater130', tmp_dir, 'top.cir', pdk_details=pdk)
        top.add_module(a, 'xa', nets={'a': 'na', 'y': 'y0',
                                       'vdd': 'vdd', 'vss': '0'})
        top.add_module(b, 'xb', nets={'a': 'na', 'y': 'y1',
                                      'vdd': 'vdd', 'vss': '0'})
        with pytest.raises(CircuitError, match='structurally different') as excinfo:
            top.generate_netlist()
        message = str(excinfo.value)
        assert "'Bias'" in message and "'bias'" in message, message
        assert 'only by case' in message, message
        # Only the first-registered spelling is ever a module_dict key.
        assert list(top.module_dict.keys()) == ['Bias']

    def test_case_variant_module_names_identical_bodies_dedup(self, pdk, tmp_dir):
        """Same body, case-variant module_name: dedups onto the FIRST spelling
        emitted — never two `.subckt` blocks for one electrical circuit."""
        import re
        from silk.circuit.modules import Module

        a = self._leaf(pdk, tmp_dir, 'Bias')
        b = self._leaf(pdk, tmp_dir, 'bias')   # identical body, case-variant name

        top = Module('PDK_skywater130', tmp_dir, 'top.cir', pdk_details=pdk)
        top.add_module(a, 'xa', nets={'a': 'na', 'y': 'y0',
                                       'vdd': 'vdd', 'vss': '0'})
        top.add_module(b, 'xb', nets={'a': 'na', 'y': 'y1',
                                       'vdd': 'vdd', 'vss': '0'})   # must not raise

        assert list(top.module_dict.keys()) == ['Bias']
        assert top.module_dict['Bias']['numberInstantiated'] == 2

        netlist = top.netlister.generate_module_definitions(top.module_dict)
        names = [m for m in re.findall(r'(?im)^\.subckt\s+(\S+)', netlist)]
        assert names == ['Bias'], (
            f'expected exactly one .subckt definition under the first-'
            f'registered spelling; got {names}')


